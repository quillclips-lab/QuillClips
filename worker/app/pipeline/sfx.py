"""SFX library: assets/sfx/<category>/*.{wav,mp3,ogg,flac,m4a}.

User files dropped into a category folder are picked up automatically and preferred. If a category
is empty we synthesize a small CC0 set (generated by this code, files prefixed `qc_`).
"""
from __future__ import annotations

import hashlib
from pathlib import Path

import numpy as np
import soundfile as sf

from ..config import MUSIC_DIR, SFX_DIR

SR = 48000
CATEGORIES = ["whoosh", "pop", "hit", "boom", "riser", "ding", "glitch"]
AUDIO_EXTS = {".wav", ".mp3", ".ogg", ".flac", ".m4a", ".aac"}
# loudness of each category relative to speech (before the global SFX volume)
CATEGORY_GAIN = {"whoosh": 0.55, "pop": 0.5, "hit": 0.7, "boom": 0.65, "riser": 0.45, "ding": 0.45, "glitch": 0.4}


def _env(n: int, attack: float, decay: float) -> np.ndarray:
    t = np.arange(n) / SR
    a = np.clip(t / max(attack, 1e-4), 0, 1)
    return a * np.exp(-np.maximum(0, t - attack) / max(decay, 1e-4))


def _lowpass_sweep(x: np.ndarray, cut_hz: np.ndarray) -> np.ndarray:
    """Time-varying one-pole low-pass (cutoff per sample)."""
    alpha = 1 - np.exp(-2 * np.pi * cut_hz / SR)
    y = np.empty_like(x)
    acc = 0.0
    for i in range(len(x)):
        acc += alpha[i] * (x[i] - acc)
        y[i] = acc
    return y


def _norm(x: np.ndarray, peak: float = 0.9) -> np.ndarray:
    m = np.max(np.abs(x)) or 1.0
    return x / m * peak


def synth(cat: str, variant: int) -> np.ndarray:
    rng = np.random.default_rng(1000 + variant * 7 + CATEGORIES.index(cat))
    v = variant
    if cat == "whoosh":
        d = 0.42 + 0.12 * v
        n = int(SR * d)
        t = np.linspace(0, 1, n)
        bell = np.sin(np.pi * t) ** 2
        cut = 300 + 5200 * bell
        noise = rng.standard_normal(n)
        mono = _lowpass_sweep(noise, cut) - 0.6 * _lowpass_sweep(noise, cut * 0.25)
        mono = _norm(mono * bell)
        pan = np.linspace(-0.7, 0.7, n) * (1 if v % 2 == 0 else -1)
        return np.stack([mono * (1 - pan) / 2 * 1.4, mono * (1 + pan) / 2 * 1.4], 1)
    if cat == "pop":
        d = 0.12
        n = int(SR * d)
        t = np.arange(n) / SR
        f = (700 + 150 * v) * np.exp(-t * 18) + 220
        x = np.sin(2 * np.pi * np.cumsum(f) / SR) * _env(n, 0.002, 0.035)
        x[:60] += rng.standard_normal(60) * 0.3
        return _norm(x)
    if cat == "hit":
        n = int(SR * 0.7)
        t = np.arange(n) / SR
        body = np.sin(2 * np.pi * (60 + 15 * v) * t) * _env(n, 0.002, 0.22)
        thump = np.sin(2 * np.pi * 140 * t) * _env(n, 0.001, 0.05)
        crack = _lowpass_sweep(rng.standard_normal(n), np.full(n, 4000.0)) * _env(n, 0.0005, 0.02)
        return _norm(body + 0.6 * thump + 0.8 * crack)
    if cat == "boom":
        n = int(SR * 1.6)
        t = np.arange(n) / SR
        f = 48 * np.exp(-t * 0.6) + 28
        sub = np.sin(2 * np.pi * np.cumsum(f) / SR) * _env(n, 0.004, 0.55)
        rumble = _lowpass_sweep(rng.standard_normal(n), np.full(n, 180.0)) * _env(n, 0.01, 0.4) * 6
        return _norm(np.tanh(1.5 * (sub + rumble)))
    if cat == "riser":
        d = 1.6 + 0.4 * v
        n = int(SR * d)
        t = np.linspace(0, 1, n)
        cut = 200 + 7000 * t ** 2
        noise = _lowpass_sweep(rng.standard_normal(n), cut)
        tone = np.sin(2 * np.pi * np.cumsum(180 + 900 * t ** 2) / SR)
        x = (0.8 * _norm(noise) + 0.35 * tone) * t ** 1.6
        x[-int(0.01 * SR):] *= np.linspace(1, 0, int(0.01 * SR))
        return _norm(x)
    if cat == "ding":
        n = int(SR * 1.4)
        t = np.arange(n) / SR
        base = 1320 * (1 + 0.25 * v)
        x = sum(a * np.sin(2 * np.pi * base * k * t) * _env(n, 0.002, 0.5 / k)
                for k, a in ((1, 1.0), (2.01, 0.45), (3.03, 0.2), (4.2, 0.08)))
        return _norm(x)
    if cat == "glitch":
        n = int(SR * 0.28)
        x = np.zeros(n)
        pos = 0
        while pos < n:
            seg = int(rng.integers(300, 2400))
            freq = float(rng.choice([180, 360, 720, 1440, 2880]))
            tt = np.arange(min(seg, n - pos)) / SR
            x[pos:pos + len(tt)] = np.sign(np.sin(2 * np.pi * freq * tt)) * rng.uniform(0.3, 1.0)
            pos += seg
        x = np.round(x * 4) / 4  # bit-crush
        return _norm(x * _env(n, 0.001, 0.2), 0.7)
    raise ValueError(cat)


def ensure_library() -> None:
    for cat in CATEGORIES:
        d = SFX_DIR / cat
        d.mkdir(parents=True, exist_ok=True)
        if any(p.suffix.lower() in AUDIO_EXTS for p in d.iterdir()):
            continue
        for v in range(2):
            sf.write(str(d / f"qc_{cat}_{v + 1}.wav"), synth(cat, v), SR, subtype="PCM_16")


def files(cat: str) -> list[Path]:
    d = SFX_DIR / cat
    if not d.exists():
        return []
    all_files = sorted(p for p in d.iterdir() if p.suffix.lower() in AUDIO_EXTS)
    user = [p for p in all_files if not p.name.startswith("qc_")]
    return user or all_files


def pick(cat: str, seed: str) -> Path | None:
    options = files(cat)
    if not options:
        ensure_library()
        options = files(cat)
    if not options:
        return None
    h = int(hashlib.md5(seed.encode()).hexdigest(), 16)
    return options[h % len(options)]


def music_tracks() -> list[Path]:
    return sorted(p for p in MUSIC_DIR.glob("**/*") if p.suffix.lower() in AUDIO_EXTS)


def library_summary() -> dict:
    ensure_library()
    out = {}
    for cat in CATEGORIES:
        fs = files(cat)
        out[cat] = {"count": len(fs), "user": any(not p.name.startswith("qc_") for p in fs)}
    n = len(music_tracks())
    out["music"] = {"count": n, "user": n > 0}
    return out
